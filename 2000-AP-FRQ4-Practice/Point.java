public class Point
{
    int row;
    int col;

    /**
     * Constructor for objects of class Point
     */
    public Point(int r, int c)
    {
        row = r;
        col = c;
    }

    public int getRow()
    {
        return row;
    }
    
    public int getCol()
    {
        return col;
    }
}